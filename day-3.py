# ------------------------------------------------------------
# 1. if, elif, else
# ------------------------------------------------------------
age = 20
if age >= 18:
    print("You are an adult")
elif age >= 13:
    print("You are a teenager")
else:
    print("You are a child")

# ------------------------------------------------------------
# 2. Nested Conditions
# ------------------------------------------------------------
has_id = True
if age >= 18:
    print("Age requirement satisfied")
    if has_id:
        print("ID verified")
    else:
        print("ID is required")
else:
    print("You are not eligible")

# ------------------------------------------------------------
# 3. for Loop
# ------------------------------------------------------------
for i in range(1, 6):
    print(i)

# ------------------------------------------------------------
# for Loop with a List
# ------------------------------------------------------------
foods = ["Biryani", "Pizza", "Burger"]
for food in foods:
    print("Food:", food)

# ------------------------------------------------------------
# 4. while Loop
# ------------------------------------------------------------
count = 1
while count <= 5:
    print(count)
    count += 1

# ------------------------------------------------------------
# 5. break
# ------------------------------------------------------------
for i in range(1, 6):
    if i == 3:
        break
    print(i)

# ------------------------------------------------------------
# 6. continue
# ------------------------------------------------------------
for i in range(1, 6):
    if i == 3:
        continue
    print(i)

# ------------------------------------------------------------
# 7. pass
# ------------------------------------------------------------
for i in range(1, 4):
    if i == 2:
        pass
    print(i)